"""Held-out sealed evaluation protocol for ECAC.

This module implements the SEEDED HOLD-OUT EVALUATION from the proposal:
  H1: M3 vs M1/M2 comparative evaluation (already done in eval_comparison.py)
  H2: Human-confirmation baseline (proportional workload on human reviewers)
  H3: Latency + annotation-burden measurements

The protocol:
  1. A sealed dataset of traces is prepared (not seen by the model during development)
  2. The evaluation is run against the sealed dataset
  3. Results are compared against the CI trace suite
  4. Metrics (latency, annotation burden) are collected

Usage:
    from effect_broker.evaluation import HeldOutEvaluation

    eval = HeldOutEvaluation()
    eval.prepare_sealed_traces(num_traces=20)
    results = eval.run_evaluation()
    eval.report()
"""

from __future__ import annotations

import time
from dataclasses import dataclass
from enum import Enum, auto

# ---- Sealed trace definitions (never revealed during development) ----
# These traces are INDEPENDENT of the T1-T20 suite.
# A real held-out evaluation would use traces generated by the evaluation team
# and locked before model development begins.


class AttackerSophistication(Enum):
    """Attacker capability levels for difficulty grading."""

    LAYPERSON = auto()  # no adversarial knowledge
    SOPHISTICATED = auto()  # knows about capability systems
    ADVANCED = auto()  # knows about ECAC specifically


@dataclass(frozen=True)
class SealedTrace:
    """A sealed adversarial trace for held-out evaluation.

    These traces are designed by the evaluation team WITHOUT knowledge of
    the current ECAC implementation. They represent realistic attack scenarios
    that should be blocked by the four-predicate gate.
    """

    trace_id: str
    description: str
    attack_class: str
    difficulty: AttackerSophistication
    expected_blocker: str  # which predicate or mechanism should block
    kill_criterion_category: str  # which kill criterion this traces


# The SEEDED TRACES are intentionally kept separate from the T1-T20 suite.
# They are NOT imported or referenced anywhere else in the codebase.
# In a real deployment, these would be in a separate locked repository.

