@dataclass
class SealedResult:
    """Result of evaluating a sealed trace."""

    trace_id: str
    allow: bool
    actual_blocker: str | None
    expected_blocker: str
    latency_ms: float
    passed: bool  # True if actual_blocker == expected_blocker


@dataclass
class EvaluationReport:
    """Summary of held-out evaluation results."""

    total_traces: int
    correct_blocker: int
    false_negatives: int  # attack ALLOWed that should have been BLOCKed
    false_positives: int  # benign operation BLOCKed incorrectly
    avg_latency_ms: float
    median_latency_ms: float


class HeldOutEvaluation:
    """Sealed held-out evaluation protocol.

    This is a simplified implementation for demonstration. A real evaluation
    would use a sealed dataset maintained by an independent evaluation team.

    Metrics collected:
      - Blocker correctness: does M3 block where it should?
      - Latency: commit gate evaluation time
      - TCB size: lines of code in TCB (approximated)
      - Annotation burden: number of explicit capability grants needed
    """

    def __init__(self) -> None:
        self.sealed_traces: list[SealedTrace] = list(SEALED_TRACES)
        self.results: list[SealedResult] = []
        self._timing_data: list[float] = []

    def run_sealed_trace(self, trace: SealedTrace) -> SealedResult:
        """Evaluate a single sealed trace against ECAC.

        Returns (allow, actual_blocker, latency_ms).
        """
        import warnings

        warnings.filterwarnings("ignore")

        from effect_broker.broker import EffectBroker
        from effect_broker.lattice import Confidentiality, Integrity
        from effect_broker.model import Capability, Commit, Data, Domain, Effect, EffectTarget, Task

        broker = EffectBroker()

        # Bootstrap minimal resources for the trace
        # NOTE: In a real evaluation, these would be inferred from the trace description
        # by the evaluation harness, NOT hardcoded here. This is a simplification.
        if "email" in trace.description or "send" in trace.attack_class:
            broker.store._unsafe_bootstrap_email("internal@corp.com", Domain.INTERNAL)
        if (
            "file" in trace.description
            or "read" in trace.attack_class
            or "write" in trace.attack_class
        ):
            broker.store._unsafe_bootstrap_file("file:///reports", Confidentiality.INTERNAL)
            broker.store._unsafe_bootstrap_file("file:///reports", Confidentiality.INTERNAL)

        # Set up a task with default ceiling
        task = Task(
            task_id="sealed-task",
            owner="User",
            ceiling=Capability(
                owner="User",
                holder="EffectBroker",
                right="*",
                target="*",
                scope=frozenset({"*"}),
                expiry=float("inf"),
                nonce="default-ceiling",
            ),
        )
        broker.register_task(task)

        # Build the effect based on attack class
        # NOTE: This is the evaluation harness constructing the effect, not the broker.
        # The broker evaluates it, it does not construct it.
        #
        # CRITICAL FIX: target must match the bootstrapped resource.
        # Email traces bootstrap internal@corp.com → effect target = internal@corp.com
        # File traces bootstrap file:///reports → effect target = file:///reports
        if trace.attack_class in (
            "capability-cycle",
            "scope-inflation",
            "time-drift",
            "session-replay",
            "exception-scope-creep",
            "integrity-violation",
            "bcc-scope-creep",
        ):
            etype = "send"
            target = "internal@corp.com"  # email target, matching bootstrap
            cap_nonce = "forged-cap"
        else:
            etype = "read"
            target = "file:///reports"
            cap_nonce = "forged-cap"

        if trace.attack_class in ("bcc-scope-creep",):
            # BCC to external domain → NoAmp should block
            broker.capabilities["send-cap"] = Capability(
                owner="User",
                holder="Agent",
                right="send",
                target="internal@corp.com",
                scope=frozenset({"internal"}),
                expiry=float("inf"),
                nonce="send-cap",
                derives_from=None,
            )
            effect = Effect(
                etype,
                target,
                {"extra_resources": ["attacker@elsewhere.com"]},
                (Data("msg", Confidentiality.INTERNAL, Integrity.USER),),
                cap_nonce,
                (),
                known_targets=EffectTarget(
                    primary=target, additional=frozenset({"attacker@elsewhere.com"})
                ),
            )
            start = time.perf_counter()
            allow, ev = broker.commit(Commit(effect, task))
            latency_ms = (time.perf_counter() - start) * 1000
            return SealedResult(
                trace_id=trace.trace_id,
                allow=allow,
                actual_blocker=ev.get("primary_blocker"),
                expected_blocker=trace.expected_blocker,
                latency_ms=latency_ms,
                passed=(ev.get("primary_blocker") == trace.expected_blocker),
            )
        effect = Effect(
            etype,
            target,
            {},
            (Data("data", Confidentiality.INTERNAL, Integrity.USER),),
            cap_nonce,
            (),
        )

        start = time.perf_counter()
        allow, ev = broker.commit(Commit(effect, task))
        latency_ms = (time.perf_counter() - start) * 1000

        return SealedResult(
            trace_id=trace.trace_id,
            allow=allow,
            actual_blocker=ev.get("primary_blocker"),
            expected_blocker=trace.expected_blocker,
            latency_ms=latency_ms,
            passed=(ev.get("primary_blocker") == trace.expected_blocker),
        )

    def run_evaluation(self) -> list[SealedResult]:
        """Run held-out evaluation on all sealed traces.

        Returns a list of SealedResult for each trace.
        """
        self.results = []
        self._timing_data = []

        for trace in self.sealed_traces:
            result = self.run_sealed_trace(trace)
            self.results.append(result)
            self._timing_data.append(result.latency_ms)

        return self.results

    def report(self) -> EvaluationReport:
        """Generate an evaluation report from held-out results."""
        if not self.results:
            self.run_evaluation()

        correct = sum(1 for r in self.results if r.passed)
        false_neg = sum(1 for r in self.results if r.allow and not r.passed)
        false_pos = sum(1 for r in self.results if not r.allow and r.passed)

        timings = sorted(self._timing_data)
        n = len(timings)
        median = timings[n // 2] if n % 2 == 1 else (timings[n // 2 - 1] + timings[n // 2]) / 2
        avg = sum(timings) / n if n > 0 else 0.0

        return EvaluationReport(
            total_traces=len(self.results),
            correct_blocker=correct,
            false_negatives=false_neg,
            false_positives=false_pos,
            avg_latency_ms=avg,
            median_latency_ms=median,
        )

    def print_report(self) -> None:
        """Print a human-readable evaluation report."""
        report = self.report()

        print("=" * 70)
        print("HELD-OUT SEEDED EVALUATION REPORT")
        print("=" * 70)
        print(f"Total traces:      {report.total_traces}")
        print(f"Correct blocker:   {report.correct_blocker}/{report.total_traces}")
        print(f"False negatives:   {report.false_negatives} (attack ALLOW'd)")
        print(f"False positives:   {report.false_positives} (benign BLOCK'd)")
        print(f"Avg latency:       {report.avg_latency_ms:.2f}ms")
        print(f"Median latency:    {report.median_latency_ms:.2f}ms")
        print()
        print("Per-trace results:")
        print(f"{'ID':<8} {'Allow':<6} {'Expected':<10} {'Actual':<10} {'Latency':<10} {'OK'}")
        print("-" * 60)
        for r in self.results:
            ok = "✓" if r.passed else "✗"
            allow_str = "ALLOW" if r.allow else "BLOCK"
            actual = str(r.actual_blocker)
            print(
                f"{r.trace_id:<8} {allow_str:<6} {r.expected_blocker:<10} "
                f"{actual:<10} {r.latency_ms:>8.2f}ms  {ok}"
            )
        print()
        coverage = report.correct_blocker / report.total_traces * 100
        print(f"Coverage: {coverage:.1f}% (correct blocker / total traces)")


if __name__ == "__main__":
    eval = HeldOutEvaluation()
    eval.print_report()
